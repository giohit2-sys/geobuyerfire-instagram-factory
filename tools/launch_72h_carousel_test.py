def main() -> None:
    if len(IDEAS) != 72:
        raise RuntimeError(f"expected 72 ideas, got {len(IDEAS)}")

    posts = json.loads(QUEUE.read_text(encoding="utf-8"))
    for post in posts:
        if post.get("status") in {"draft", "ready", "needs_review"}:
            post["status"] = "archived"
            post["archive_reason"] = "replaced_by_72h_variant_1_test"

    now = datetime.now(TZ)
    first_slot = now.replace(minute=0, second=0, microsecond=0) + timedelta(hours=1)
    for index, (hook, payoff, topic) in enumerate(IDEAS):
        scheduled = first_slot + timedelta(hours=index)
        posts.append({
            "id": f"hf72-{scheduled:%Y%m%d-%H}-{index + 1:02d}",
            "title": hook,
            "topic": topic,
            "experiment": "72h-24-per-day-cover-variant-1",
            "slides": [hook, payoff],
            "caption": CAPTIONS[index % len(CAPTIONS)],
            "rights_status": "original",
            "commercial": False,
            "commercial_reviewed": True,
            "scheduled_at": scheduled.isoformat(),
            "status": "draft",
        })

    QUEUE.write_text(json.dumps(posts, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "queued": 72,
        "first_slot": first_slot.isoformat(),
        "last_slot": (first_slot + timedelta(hours=71)).isoformat(),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
